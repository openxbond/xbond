export type TextKey = keyof typeof extra | keyof typeof shared;
export function language(preference: string): Lang {
  return preference === "system"
    ? getDefaultLanguage()
    : (locales.find((lang) => lang === preference) ?? getDefaultLanguage());
}
export function translator(lang: Lang) {
  return (key: TextKey): string => {
    if (key in extra)
      return extra[key as keyof typeof extra][locales.indexOf(lang)];
    const [namespace, path] = shared[key as keyof typeof shared];
    const value: unknown =
      i18n.getResource(lang, namespace, path) ??
      i18n.getResource("en_US", namespace, path);
    if (typeof value !== "string")
      throw new Error(`Missing client message: ${namespace}.${path}`);
    return value;
  };
}
